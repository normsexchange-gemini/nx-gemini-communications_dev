  public getListings(params: {
    q?: string;
    category?: string;
    type?: string;
    corridor?: string;
    minPrice?: number;
    maxPrice?: number;
    condition?: string;
    status?: string;
    verifiedOnly?: boolean;
    sortBy?: "match" | "margin" | "price-desc" | "price-asc" | "newest";
    page?: number;
    limit?: number;
  }) {
    this.reloadIfNeeded();
    let result = [...this.db.listings];

    // Filter by status (Default: all except hard deleted; or active/matched/sold/delisted)
    if (params.status && params.status !== "ALL") {
      if (params.status === "ACTIVE_ONLY") {
        result = result.filter(item => !item.status || item.status === "Active" || item.status === "Matched" || item.status === "Indexed" || item.status === "Dispatched to Shopify");
      } else if (params.status === "PRUNED_OR_SOLD") {
        result = result.filter(item => item.status === "Sold" || item.status === "Delisted" || item.status === "Archived");
      } else {
        result = result.filter(item => item.status === params.status);
      }
    }

    // Filter by type
    if (params.type && params.type !== "ALL") {
      if (params.type === "MATCHED") {
        result = result.filter(item => (item.matchScore || 0) > 0);
      } else {
        result = result.filter(item => item.type === params.type);
      }
    }

    // Filter by category
    if (params.category && params.category !== "All") {
      result = result.filter(item => item.category === params.category);
    }

    // Filter by corridor
    if (params.corridor && params.corridor !== "ALL") {
      if (params.corridor === "LA_TO_VN") {
        result = result.filter(item => (item.tags || []).some(t => t.includes("LA ➔ Vietnam") || t.includes("Target:Vietnam")));
      } else if (params.corridor === "VN_TO_US") {
        result = result.filter(item => (item.tags || []).some(t => t.includes("Vietnam ➔ US") || t.includes("Target:USA")));
      } else if (params.corridor === "DOMESTIC_US") {
        result = result.filter(item => (item.contact?.location || "").includes("USA") || (item.contact?.location || "").includes("CA"));
      } else if (params.corridor === "DOMESTIC_VN") {
        result = result.filter(item => (item.contact?.location || "").includes("Vietnam"));
      }
    }

    // Filter by price range
    if (params.minPrice !== undefined && !isNaN(params.minPrice)) {
      result = result.filter(item => item.priceTarget >= params.minPrice!);
    }
    if (params.maxPrice !== undefined && !isNaN(params.maxPrice)) {
      result = result.filter(item => item.priceTarget <= params.maxPrice!);
    }

    // Filter by condition
    if (params.condition && params.condition !== "All") {
      result = result.filter(item => item.condition === params.condition);
    }

    // Filter by verified status
    if (params.verifiedOnly) {
      result = result.filter(item => item.contact?.verifiedStatus === "Verified");
    }

    // Search query across fields
    if (params.q && params.q.trim()) {
      const q = params.q.toLowerCase().trim();
      result = result.filter(item => {
        const inTitle = item.title?.toLowerCase().includes(q);
        const inMake = item.make?.toLowerCase().includes(q);
        const inModel = item.model?.toLowerCase().includes(q);
        const inPart = item.partNumber?.toLowerCase().includes(q);
        const inDesc = item.description?.toLowerCase().includes(q);
        const inEntity = item.contact?.entityName?.toLowerCase().includes(q);
        const inLocation = item.contact?.location?.toLowerCase().includes(q);
        const inContactPerson = item.contact?.contactPerson?.toLowerCase().includes(q);
        const inTags = item.tags?.some(t => t.toLowerCase().includes(q));
        const inSpecs = item.specs ? Object.entries(item.specs).some(([k, v]) => 
          k.toLowerCase().includes(q) || String(v).toLowerCase().includes(q)
        ) : false;

        return inTitle || inMake || inModel || inPart || inDesc || inEntity || inLocation || inContactPerson || inTags || inSpecs;
      });
    }

    // Sorting
    const sort = params.sortBy || "match";
    result.sort((a, b) => {
      if (sort === "match") {
        return (b.matchScore || 0) - (a.matchScore || 0);
      }
      if (sort === "margin") {
        return (b.marginSpreadEstimate || 0) - (a.marginSpreadEstimate || 0);
      }
      if (sort === "price-desc") {
        return b.priceTarget - a.priceTarget;
      }
      if (sort === "price-asc") {
        return a.priceTarget - b.priceTarget;
      }
      // newest
      return new Date(b.discoveredAt).getTime() - new Date(a.discoveredAt).getTime();
    });

    return result;
  }

